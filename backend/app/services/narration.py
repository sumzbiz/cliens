"""Turns a question and its options into playable Tamil audio.

The Tamil wording itself lives in the frontend, next to the English it mirrors, so
the two cannot drift apart. This module receives finished text and is responsible
only for making it speakable: splitting it under the API's length limit, caching
the result, and stitching the pieces into one file.
"""

from __future__ import annotations

import hashlib
import io
import wave
from collections import OrderedDict

from app.core import constants
from app.core.logging import get_logger
from app.external.sarvam import SarvamTtsClient, VoiceUnavailableError, synthesise_all

logger = get_logger(__name__)

#: Synthesised audio, most-recently-used last.
#:
#: Narration covers a small fixed set of questions, so this fills once and then
#: makes every repeat free and instant. Keyed by content, so changing a question's
#: wording produces a new key and the stale audio simply ages out rather than
#: being served for text that no longer exists.
_CACHE: OrderedDict[str, bytes] = OrderedDict()


def cache_key(text: str, speaker: str, language: str) -> str:
    """Content hash identifying one synthesised narration."""
    digest = hashlib.sha256(f"{language}|{speaker}|{text}".encode()).hexdigest()
    return digest[:32]


def split_for_synthesis(text: str) -> list[str]:
    """Split text into pieces the API will accept.

    Splits on sentence ends rather than at a fixed offset. A cut mid-sentence is
    audible — the voice drops pitch as though the sentence finished — so the
    boundary is chosen where a reader would pause anyway. A single sentence longer
    than the limit is still cut hard, because the alternative is no audio at all.
    """
    text = " ".join(text.split())
    if len(text) <= constants.SARVAM_CHUNK_TARGET_CHARACTERS:
        return [text] if text else []

    chunks: list[str] = []
    remaining = text

    while remaining:
        if len(remaining) <= constants.SARVAM_CHUNK_TARGET_CHARACTERS:
            chunks.append(remaining)
            break

        window = remaining[: constants.SARVAM_CHUNK_TARGET_CHARACTERS]
        # Tamil uses the same full stop and question mark as English here, since
        # the narration text is generated by us rather than typed by a user.
        split_at = max(window.rfind(". "), window.rfind("? "), window.rfind("! "))
        if split_at == -1:
            split_at = window.rfind(" ")
        if split_at == -1:
            split_at = constants.SARVAM_CHUNK_TARGET_CHARACTERS - 1

        chunks.append(remaining[: split_at + 1].strip())
        remaining = remaining[split_at + 1 :].strip()

    return [chunk for chunk in chunks if chunk]


def concatenate_wav(parts: list[bytes]) -> bytes:
    """Join several WAV files into one.

    Returning one file rather than a list is what makes the playback continuous:
    the browser sees a single audio source, so there is no gap between chunks
    while a second request is fetched and decoded.

    Raises:
        VoiceUnavailableError: If a part is not readable WAV audio.
    """
    if not parts:
        raise VoiceUnavailableError("Nothing to synthesise.", service="sarvam")
    if len(parts) == 1:
        return parts[0]

    buffer = io.BytesIO()
    writer: wave.Wave_write | None = None
    try:
        for part in parts:
            with wave.open(io.BytesIO(part), "rb") as reader:
                if writer is None:
                    writer = wave.open(buffer, "wb")
                    # Copy the format from the first part. Every part comes from
                    # the same model and voice, so they agree; taking it from the
                    # audio rather than assuming a rate avoids silent resampling
                    # bugs if Sarvam ever changes its output format.
                    writer.setparams(reader.getparams())
                writer.writeframes(reader.readframes(reader.getnframes()))
    except wave.Error as error:
        raise VoiceUnavailableError(
            "The voice service returned audio that could not be joined.",
            service="sarvam",
        ) from error
    finally:
        if writer is not None:
            writer.close()

    return buffer.getvalue()


class NarrationService:
    """Produces one audio file for a question and its options."""

    def __init__(self, client: SarvamTtsClient, *, speaker: str, language: str) -> None:
        """Bind the service to a configured TTS client."""
        self._client = client
        self._speaker = speaker
        self._language = language

    @property
    def available(self) -> bool:
        """Whether narration can be produced at all."""
        return self._client.configured

    async def narrate(self, text: str) -> tuple[bytes, bool]:
        """Audio for the given text, and whether it came from cache.

        Raises:
            VoiceUnavailableError: If synthesis fails on every configured key.
        """
        key = cache_key(text, self._speaker, self._language)
        cached = _CACHE.get(key)
        if cached is not None:
            _CACHE.move_to_end(key)
            logger.info("narration_cache_hit", key=key, characters=len(text))
            return cached, True

        chunks = split_for_synthesis(text)
        if not chunks:
            raise VoiceUnavailableError("Nothing to narrate.", service="sarvam")

        logger.info("narration_synthesising", key=key, chunks=len(chunks))
        audio = concatenate_wav(await synthesise_all(self._client, chunks))

        _CACHE[key] = audio
        while len(_CACHE) > constants.VOICE_CACHE_ENTRIES:
            _CACHE.popitem(last=False)

        return audio, False
