"""SQLAlchemy ORM models.

These live in the repository layer because it is the only layer permitted to touch
the database. Putting them anywhere more visible would invite services to import
them and query directly, which the layering in CLAUDE.md forbids.

All geometry is stored in WGS84 (EPSG:4326). Timestamps are stored with time zone
and generated by the database, so ordering is consistent regardless of the clock on
whichever application instance handled the write.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from geoalchemy2 import Geometry
from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core import constants
from app.core.database import Base


def _quoted_csv(values: tuple[str, ...]) -> str:
    """Render values as a SQL ``IN`` list, so CHECK constraints track the constants."""
    return ", ".join(f"'{value}'" for value in values)


class TimestampedBase(Base):
    """Mixin supplying database-generated creation timestamps."""

    __abstract__ = True

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        index=True,
    )


class Site(TimestampedBase):
    """A building site: the polygon a user drew, plus its computed area.

    The polygon is the authoritative geometry. ``area_sq_ft`` is computed by the
    backend from that geometry rather than trusted from the client, which sends its
    own turf.js figure only for display.
    """

    __tablename__ = "sites"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )

    # POLYGON in EPSG:4326. spatial_index creates a GiST index, without which any
    # spatial lookup degrades to a sequential scan.
    geometry: Mapped[Any] = mapped_column(
        Geometry(geometry_type="POLYGON", srid=constants.WGS84_SRID, spatial_index=True),
        nullable=False,
    )

    # Server-computed from `geometry`; never accepted from the client.
    area_sq_ft: Mapped[float] = mapped_column(Float, nullable=False)

    # Centroid coordinates, denormalised at write time. They key the external-data
    # cache and are read on every score, so storing them avoids recomputing
    # ST_Centroid on each request.
    centroid_longitude: Mapped[float] = mapped_column(Float, nullable=False)
    centroid_latitude: Mapped[float] = mapped_column(Float, nullable=False)

    # Optional user-supplied name for the site.
    label: Mapped[str | None] = mapped_column(String(200), nullable=True)

    scores: Mapped[list[Score]] = relationship(
        back_populates="site",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    __table_args__ = (
        CheckConstraint(
            f"area_sq_ft >= {constants.MIN_FLOOR_AREA_SQ_FT} "
            f"AND area_sq_ft <= {constants.MAX_FLOOR_AREA_SQ_FT}",
            name="area_within_supported_bounds",
        ),
        CheckConstraint(
            f"centroid_longitude >= {constants.MIN_LONGITUDE} "
            f"AND centroid_longitude <= {constants.MAX_LONGITUDE}",
            name="centroid_longitude_valid",
        ),
        CheckConstraint(
            f"centroid_latitude >= {constants.MIN_LATITUDE} "
            f"AND centroid_latitude <= {constants.MAX_LATITUDE}",
            name="centroid_latitude_valid",
        ),
    )


class Material(TimestampedBase):
    """A construction material and its documented hazard resistance ratings.

    Resistance is dimensionless in ``[0, 1]``: the share of that hazard's load the
    material resists. ``source_reference`` records where each rating came from and is
    required — an undocumented rating is not admissible in a permit context.
    """

    __tablename__ = "materials"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )

    # Stable, human-readable identifier used by the API and the frontend, e.g.
    # "fired_clay_brick". Clients reference materials by this, never by UUID.
    code: Mapped[str] = mapped_column(String(80), nullable=False, unique=True)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    component: Mapped[str] = mapped_column(String(20), nullable=False, index=True)

    resistance_wind: Mapped[float] = mapped_column(Float, nullable=False)
    resistance_flood: Mapped[float] = mapped_column(Float, nullable=False)
    resistance_heat: Mapped[float] = mapped_column(Float, nullable=False)

    # Relative installed cost, indexed so the baseline conventional option for each
    # component is 1.0. Used to rank recommendations by cost, not to price a build.
    relative_cost_index: Mapped[float] = mapped_column(Float, nullable=False, default=1.0)

    source_reference: Mapped[str] = mapped_column(Text, nullable=False)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    __table_args__ = (
        CheckConstraint(
            f"component IN ({_quoted_csv(constants.BUILDING_COMPONENTS)})",
            name="component_is_known",
        ),
        CheckConstraint(
            "resistance_wind BETWEEN 0 AND 1 "
            "AND resistance_flood BETWEEN 0 AND 1 "
            "AND resistance_heat BETWEEN 0 AND 1",
            name="resistances_within_unit_interval",
        ),
        CheckConstraint("relative_cost_index > 0", name="cost_index_positive"),
    )


class Score(TimestampedBase):
    """A computed Climate Lien Score and the full breakdown behind it.

    ``input_hash`` makes scoring idempotent: the same site, materials and model
    versions resolve to an existing row instead of recomputing. Model versions are
    part of that hash, so retraining correctly produces a new score rather than
    silently reusing one from a superseded model.
    """

    __tablename__ = "scores"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    site_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("sites.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # SHA-256 over the canonicalised scoring inputs; 64 hex characters.
    input_hash: Mapped[str] = mapped_column(String(64), nullable=False)

    # "baseline" for the user's own materials, "improved" for the re-scored
    # recommendation. Both are persisted so the prove step is auditable.
    scenario: Mapped[str] = mapped_column(String(20), nullable=False)

    # The score itself: the first year the site becomes uninsurable. NULL means the
    # threshold is never crossed within the horizon, which is materially different
    # from crossing in the final year and is presented differently.
    crossing_year: Mapped[int | None] = mapped_column(Integer, nullable=True)

    # 95% interval on the crossing year, and the qualitative label derived from it.
    crossing_year_lower: Mapped[int | None] = mapped_column(Integer, nullable=True)
    crossing_year_upper: Mapped[int | None] = mapped_column(Integer, nullable=True)
    confidence_label: Mapped[str] = mapped_column(String(20), nullable=False)

    # Full auditable decomposition: per-year damage ratios, per-component and
    # per-hazard stress contributions, and the resolved material set.
    breakdown: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)

    # Which artifacts produced this score, so an old score stays interpretable.
    damage_model_version: Mapped[str] = mapped_column(String(120), nullable=False)
    material_model_version: Mapped[str] = mapped_column(String(120), nullable=False)

    site: Mapped[Site] = relationship(back_populates="scores")
    reports: Mapped[list[Report]] = relationship(
        back_populates="score",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    __table_args__ = (
        UniqueConstraint("input_hash", "scenario", name="uq_scores_input_hash_scenario"),
        CheckConstraint(
            "scenario IN ('baseline', 'improved')",
            name="scenario_is_known",
        ),
        CheckConstraint(
            f"crossing_year IS NULL OR (crossing_year >= {constants.HORIZON_START_YEAR} "
            f"AND crossing_year <= {constants.HORIZON_END_YEAR})",
            name="crossing_year_within_horizon",
        ),
        CheckConstraint(
            "confidence_label IN ('high', 'moderate', 'low')",
            name="confidence_label_is_known",
        ),
    )


class Report(TimestampedBase):
    """A plain-English report generated from a score breakdown.

    ``prompt_version`` records which version-controlled prompt produced the text, so
    a report can always be traced to the exact instructions behind it.
    """

    __tablename__ = "reports"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    score_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("scores.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    content: Mapped[str] = mapped_column(Text, nullable=False)
    prompt_version: Mapped[str] = mapped_column(String(20), nullable=False)
    model_name: Mapped[str] = mapped_column(String(80), nullable=False)

    score: Mapped[Score] = relationship(back_populates="reports")


class ExternalResponseCache(TimestampedBase):
    """Durable cache of third-party responses.

    Two jobs. It keeps re-scoring deterministic — the brief requires that a re-score
    cannot drift because an upstream changed between calls — and it keeps the app
    inside the free-tier quotas of Earth Engine and Gemini.

    Payloads are stored exactly as received (already parsed to JSON) so a cached
    result is interpreted by the same code path as a fresh one.
    """

    __tablename__ = "external_response_cache"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )

    service: Mapped[str] = mapped_column(String(40), nullable=False)
    # Deterministic key over the request parameters: rounded centroid, year range,
    # dataset identifier. Built by the repository, never by a caller.
    cache_key: Mapped[str] = mapped_column(String(200), nullable=False)

    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    __table_args__ = (
        UniqueConstraint("service", "cache_key", name="uq_external_cache_service_key"),
        # Supports the "fetch a live entry" lookup, which always filters on both
        # the key and the expiry.
        Index("ix_external_cache_lookup", "service", "cache_key", "expires_at"),
        CheckConstraint(
            "service IN ('earth_engine', 'imd', 'gemini')",
            name="service_is_known",
        ),
    )
